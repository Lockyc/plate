package raster

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writePAM(t *testing.T, header string, pix []byte) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), "a.pam")
	if err := os.WriteFile(p, append([]byte(header), pix...), 0o644); err != nil {
		t.Fatal(err)
	}
	return p
}

func TestReadPAM(t *testing.T) {
	p := writePAM(t, "P7\nWIDTH 2\nHEIGHT 1\nDEPTH 4\nMAXVAL 255\nTUPLTYPE CMYK\n# Image generated by GPL Ghostscript\nENDHDR\n", []byte{1, 2, 3, 4, 5, 6, 7, 8})
	img, err := ReadPAM(p)
	if err != nil {
		t.Fatal(err)
	}
	if img.W != 2 || img.H != 1 || len(img.Pix) != 8 || img.Pix[7] != 8 {
		t.Errorf("got %dx%d with %d bytes", img.W, img.H, len(img.Pix))
	}
	rgb := writePAM(t, "P7\nWIDTH 1\nHEIGHT 1\nDEPTH 3\nMAXVAL 255\nTUPLTYPE RGB\nENDHDR\n", []byte{1, 2, 3})
	if _, err := ReadPAM(rgb); err == nil || !strings.Contains(err.Error(), "CMYK") {
		t.Errorf("RGB PAM: %v", err)
	}
	short := writePAM(t, "P7\nWIDTH 2\nHEIGHT 1\nDEPTH 4\nMAXVAL 255\nTUPLTYPE CMYK\nENDHDR\n", []byte{1, 2, 3})
	if _, err := ReadPAM(short); err == nil {
		t.Error("a truncated PAM was accepted")
	}
}
