// pamBytes is a w x h P7 file filled by f.
func pamBytes(w, h int, f func(x, y int) [4]byte) []byte {
	b := []byte("P7\nWIDTH " + strconv.Itoa(w) + "\nHEIGHT " + strconv.Itoa(h) + "\nDEPTH 4\nMAXVAL 255\nTUPLTYPE CMYK\n# Image generated by GPL Ghostscript\nENDHDR\n")
	for y := range h {
		for x := range w {
			c := f(x, y)
			b = append(b, c[:]...)
		}
	}
	return b
}

func block(x0, y0, size int, c [4]byte) func(x, y int) [4]byte {
	return func(x, y int) [4]byte {
		if x >= x0 && x < x0+size && y >= y0 && y < y0+size {
			return c
		}
		return [4]byte{0, 0, 0, 255}
	}
}

func pamImg(w, h int, f func(x, y int) [4]byte) raster.PAM {
	img := raster.PAM{W: w, H: h}
	for y := range h {
		for x := range w {
			c := f(x, y)
			img.Pix = append(img.Pix, c[:]...)
		}
	}
	return img
}

func TestInkLimit(t *testing.T) {
	const dpi = 254 // 1 px = 0.1 mm
	full := [4]byte{255, 255, 255, 255}
	if _, over := inkLimit(pamImg(100, 100, block(0, 0, 0, full)), 300, dpi); over {
		t.Error("plain black is over 300%")
	}
	got, over := inkLimit(pamImg(100, 100, block(40, 40, 20, full)), 300, dpi)
	if !over || got.Peak != 400 {
		t.Fatalf("20x20 block at 400%%: %+v over %v", got, over)
	}
	for i, w := range []float64{0.4, 0.4, 0.2, 0.2} {
		if g := []float64{got.Box.X, got.Box.Y, got.Box.W, got.Box.H}[i]; math.Abs(g-w) > 0.01 {
			t.Errorf("box %+v, want 0.4,0.4,0.2,0.2", got.Box)
		}
	}
	if got, over := inkLimit(pamImg(100, 100, block(40, 40, 5, full)), 300, dpi); over {
		t.Errorf("a 0.25 mm² speck is over: %+v", got)
	}
}

func TestPressInkRefusesPage2(t *testing.T) {
	e := setup(t)
	t.Setenv("PAGES", "2")
	t.Setenv("PAGE_LINES", "Page    1 size: 900 x 675 pts\nPage    2 size: 900 x 675 pts")
	dir := t.TempDir()
	good := filepath.Join(dir, "1.pam")
	bad := filepath.Join(dir, "2.pam")
	os.WriteFile(good, pamBytes(100, 100, block(0, 0, 0, [4]byte{0, 0, 0, 255})), 0o644)
	os.WriteFile(bad, pamBytes(100, 100, block(20, 20, 40, [4]byte{255, 255, 255, 255})), 0o644)
	t.Setenv("PAM_1", good)
	t.Setenv("PAM_2", bad)
	if code := e.run(); code != 1 {
		t.Fatalf("code %d: %s", code, e.stderr.String())
	}
	for _, want := range []string{"page 2", "ink"} {
		if !strings.Contains(e.stderr.String(), want) {
			t.Errorf("stderr %q lacks %q", e.stderr.String(), want)
		}
	}
	if !strings.Contains(e.stdout.String(), "page 1: peak ink 100%") {
		t.Errorf("stdout %q lacks page 1's peak ink", e.stdout.String())
	}
	if e.outExists() {
		t.Error("an over-inked master was left behind")
	}
}

